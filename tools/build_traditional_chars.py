"""Generate the character tables between traditional and simplified Chinese
that the traditional variant needs (src/engine/nc_traditional_chars.inc).
The character LM was trained on simplified text: a traditional text is
scored as its simplified characters. A character that traditional text
never writes (对, 这, 发) is shown in its traditional form; one that
traditional text writes as well (后: 後 or 后) is left as it is.

The traditional forms are Taiwan's, as the traditional dictionary writes its
function words (為, 裡, 著, 說): OpenCC's STCharacters.txt (each simplified
character with its traditional forms, the first taken) followed by
TWVariants.txt (爲 -> 為, 裏 -> 裡), as OpenCC's s2tw does. Two characters
are added by hand:
- 着 -> 著. STCharacters has no row for 着 (OpenCC's standard writes the
  particle 着); TWVariants turns it into 著, and the dictionary writes the
  particle so (接著, 看著).
- 著 -> 着 for the LM, which saw the particle written 着. 著 stays where it
  reads zhu (著名, 顯著, 名著): the words of TWVariantsRevPhrases.txt that
  hold it and those in KEPT_EXTRA.

TSCharacters.txt gives each traditional character its first simplified
form. All at a fixed commit. Characters outside the Basic Multilingual Plane
are left out: the tables map UTF-16 code units.

usage: build_traditional_chars.py
"""
import hashlib
from pathlib import Path
import urllib.request

COMMIT = '556ed22496d650bd0b13b6c163be9814637970ae'   # OpenCC ver.1.1.9
BASE = f'https://raw.githubusercontent.com/BYVoid/OpenCC/{COMMIT}/data/dictionary/'
ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'src/engine/nc_traditional_chars.inc'
PARTICLE_SIMPLIFIED, PARTICLE_TRADITIONAL = '着', '著'
# Words of 著 read zhu that TWVariantsRevPhrases.txt does not list.
KEPT_EXTRA = ['土著', '原著', '卓著', '遺著', '編著', '論著', '譯著', '專著', '拙著', '新著']


def fetch(name):
    with urllib.request.urlopen(BASE + name, timeout=30) as response:
        return response.read()


def entries(payload):
    for line in payload.decode('utf-8').splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        key, values = line.split('\t')
        yield key, values.split(' ')


def bmp(text):
    return len(text) == 1 and ord(text) <= 0xFFFF


def table(name, codes):
    lines = [f'const {name}: array[0..{len(codes) - 1}] of Word = (']
    for start in range(0, len(codes), 12):
        suffix = ',' if start + 12 < len(codes) else ');'
        lines.append('    ' + ', '.join(f'${code:04X}' for code in codes[start:start + 12]) + suffix)
    return '\n'.join(lines)


def string_table(name, words):
    # Code points: the sources are read in the system code page.
    lines = [f'const {name}: array[0..{len(words) - 1}] of string = (']
    for start in range(0, len(words), 8):
        suffix = ',' if start + 8 < len(words) else ');'
        lines.append('    ' + ', '.join(''.join(f'#${ord(ch):04X}' for ch in word)
                                          for word in words[start:start + 8]) + suffix)
    return '\n'.join(lines)


def main():
    payloads = {name: fetch(name) for name in
                ('TSCharacters.txt', 'STCharacters.txt', 'TWVariants.txt', 'TWVariantsRevPhrases.txt')}
    taiwan = {key: values[0] for key, values in entries(payloads['TWVariants.txt'])}
    to_simplified = {}
    for key, values in entries(payloads['TSCharacters.txt']):
        if bmp(key) and bmp(values[0]) and key != values[0]:
            to_simplified[ord(key)] = ord(values[0])
    to_simplified[ord(PARTICLE_TRADITIONAL)] = ord(PARTICLE_SIMPLIFIED)
    to_traditional = {}
    ambiguous = []
    for key, values in entries(payloads['STCharacters.txt']):
        if not bmp(key):
            continue
        forms = list(dict.fromkeys(taiwan.get(value, value) for value in values))
        if key in forms:
            if len(forms) > 1:
                ambiguous.append(ord(key))
        elif bmp(forms[0]):
            to_traditional[ord(key)] = ord(forms[0])
    to_traditional[ord(PARTICLE_SIMPLIFIED)] = ord(PARTICLE_TRADITIONAL)
    kept = sorted({key for key, _ in entries(payloads['TWVariantsRevPhrases.txt'])
                   if PARTICLE_TRADITIONAL in key} | set(KEPT_EXTRA))
    t_keys = sorted(to_simplified)
    s_keys = sorted(to_traditional)
    sums = ''.join(f'  {name} SHA256: {hashlib.sha256(payload).hexdigest()}\n'
                   for name, payload in payloads.items())
    header = ('{ Generated by tools/build_traditional_chars.py. Do not edit.\n'
              '  OpenCC (https://github.com/BYVoid/OpenCC), Apache License 2.0,\n'
              f'  commit {COMMIT} (ver.1.1.9).\n' + sums +
              '  c_traditional_chars / c_traditional_simplified: a traditional character\n'
              '  and its first simplified form, sorted (著 -> 着 added).\n'
              '  c_traditional_kept_words: words in which 著 stays (著名, 顯著).\n'
              '  c_simplified_chars / c_simplified_traditional: a character traditional\n'
              '  text never writes and its traditional form, Taiwan\'s (為 for 为, 著 for\n'
              '  着). c_simplified_ambiguous: one that traditional text writes as well,\n'
              '  beside other forms (后: 後 or 后).\n'
              '  UTF-16 code units of the Basic Multilingual Plane only. }\n')
    text = '\n\n'.join([header.rstrip('\n'),
                        table('c_traditional_chars', t_keys),
                        table('c_traditional_simplified', [to_simplified[k] for k in t_keys]),
                        string_table('c_traditional_kept_words', kept),
                        table('c_simplified_chars', s_keys),
                        table('c_simplified_traditional', [to_traditional[k] for k in s_keys]),
                        table('c_simplified_ambiguous', sorted(ambiguous))]) + '\n'
    TARGET.write_text(text, encoding='utf-8', newline='\n')
    print(f'{TARGET}: {len(t_keys)} traditional, {len(s_keys)} simplified, '
          f'{len(ambiguous)} ambiguous, {len(kept)} kept words')


if __name__ == '__main__':
    main()
